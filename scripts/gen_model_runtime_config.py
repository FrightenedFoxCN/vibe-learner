"""Generate browser and backend model settings from one versioned specification."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "packages/shared/fixtures/model-runtime-config-v1.json"
PYTHON = ROOT / "services/ai/app/core/model_runtime_limits.py"
TYPESCRIPT = ROOT / "packages/shared/src/model-runtime-config.ts"
BEGIN = "# BEGIN GENERATED BROWSER SETTINGS\n"
END = "# END GENERATED BROWSER SETTINGS"

FIELDS = {
    "timeout_seconds": ("timeoutSeconds", "PROVIDER_TIMEOUT_SECONDS"),
    "setting_temperature": ("settingTemperature", "MODEL_TEMPERATURE"),
    "chat_temperature": ("chatTemperature", "MODEL_TEMPERATURE"),
    "setting_max_tokens": ("settingMaxTokens", "MODEL_MAX_TOKENS"),
    "chat_max_tokens": ("chatMaxTokens", "MODEL_MAX_TOKENS"),
    "chat_history_messages": ("chatHistoryMessages", "CHAT_HISTORY_MESSAGES"),
    "chat_tool_max_rounds": ("chatToolMaxRounds", "CHAT_TOOL_MAX_ROUNDS"),
}


TOKEN_POLICY = {
    "structured_generation_tokens": (
        "structuredGenerationTokens",
        "STRUCTURED_GENERATION_MAX_TOKENS",
    ),
    "study_recovery_min_tokens": (
        "studyRecoveryMinTokens",
        "STUDY_CHAT_RECOVERY_MIN_TOKENS",
    ),
    "tavern_recovery_min_tokens": (
        "tavernRecoveryMinTokens",
        "TAVERN_ACTOR_RECOVERY_MIN_TOKENS",
    ),
}


def generate_python(spec):
    before, _, rest = PYTHON.read_text(encoding="utf-8").partition(BEGIN)
    _, separator, after = rest.partition(END)
    if not separator:
        raise ValueError("missing Python generation markers")
    names = [
        f"DEFAULT_MODEL_NAME = {json.dumps(spec['default_model_name'])}",
        f"DEFAULT_EMBEDDING_MODEL = {json.dumps(spec['default_embedding_model'])}",
    ]
    defaults, ranges = [], {}
    for field, (_, shared) in FIELDS.items():
        item = spec[field]
        default_name = shared if field == "timeout_seconds" else field.upper()
        defaults.append(f"DEFAULT_{default_name} = {item['default']!r}")
        pair = (item["min"], item["max"])
        if shared in ranges and ranges[shared] != pair:
            raise ValueError(f"fields sharing {shared} must have identical bounds")
        ranges[shared] = pair
    lines = [*names, "", *defaults, ""]
    for key, (low, high) in ranges.items():
        lines.extend([f"{key}_MIN = {low!r}", f"{key}_MAX = {high!r}"])
    lines.append("")
    for field, (_, constant) in TOKEN_POLICY.items():
        lines.append(f"{constant} = {spec['request_token_policy'][field]!r}")
    return before + BEGIN + "\n".join(lines) + "\n" + END + after


def generate_typescript(spec):
    fields = {
        "default_model_name": "defaultModelName",
        "default_embedding_model": "defaultEmbeddingModel",
        **{key: names[0] for key, names in FIELDS.items()},
    }
    lines = [
        "/** Generated by scripts/gen_model_runtime_config.py; do not edit directly. */",
        "export const MODEL_RUNTIME_CONFIG = Object.freeze({",
    ]
    for key, name in fields.items():
        value = spec[key]
        if isinstance(value, dict):
            body = ", ".join(f"{k}: {v}" for k, v in value.items())
            rendered = "{ " + body + " }"
        else:
            rendered = json.dumps(value)
        lines.append(f"  {name}: {rendered},")
    lines.extend(
        [
            "} as const);",
            "",
            "export const MODEL_REQUEST_TOKEN_POLICY = Object.freeze({",
        ]
    )
    for field, (name, _) in TOKEN_POLICY.items():
        lines.append(f"  {name}: {spec['request_token_policy'][field]},")
    lines.extend(
        [
            "} as const);",
            "",
            "export const modelRuntimeConfigSnapshot = () => ({",
            f"  schema_version: {json.dumps(spec['schema_version'])},",
        ]
    )
    lines.extend(
        f"  {key}: MODEL_RUNTIME_CONFIG.{name}," for key, name in fields.items()
    )
    lines.append("  request_token_policy: {")
    for field, (name, _) in TOKEN_POLICY.items():
        lines.append(f"    {field}: MODEL_REQUEST_TOKEN_POLICY.{name},")
    return "\n".join([*lines, "  },", "});", ""])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    dirty = []
    for path, rendered in (
        (PYTHON, generate_python(spec)),
        (TYPESCRIPT, generate_typescript(spec)),
    ):
        if path.read_text(encoding="utf-8") == rendered:
            continue
        if args.check:
            dirty.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(rendered, encoding="utf-8")
    if dirty:
        parser.exit(1, "Stale model configuration: " + ", ".join(dirty) + "\n")


if __name__ == "__main__":
    main()
